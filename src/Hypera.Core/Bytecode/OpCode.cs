    JumpFunc = 0x0099,
    JumpFuncDynamic = 0x009A,
    TryJumpFunc = 0x009B,
    CatchEnter = 0x009C,
    CatchLeave = 0x009D,
    ReturnVoid = 0x009E,
    ReturnInt = 0x009F,
    ReturnStr = 0x00A0,
    BeginSystemPhase = 0x00A1,

    // Stackless Suspension & Input
    WaitInput = 0x00B0,
    YieldFrame = 0x00B1,
    AwaitMillis = 0x00B2,

    // Console & Rich Layout Output
    Print = 0x00C0,
    PrintLine = 0x00C1,
    PrintWait = 0x00C2,
    PrintSingle = 0x00C3,
    PrintColumn = 0x00C4,
    PrintButton = 0x00C5,
    PrintBar = 0x00C6,
    DrawLine = 0x00C7,
    ClearLine = 0x00C8,
    ReuseLastLine = 0x00C9,
    HtmlPrint = 0x00CA,
    PrintImg = 0x00CB,
    PrintShape = 0x00CC,
    SetColor = 0x00CD,
    SetBgColor = 0x00CE,
    SetStyle = 0x00CF,
    SetAlignment = 0x00D0,
    SetFont = 0x00D1,

    // Graphics, Sprites & Client Background (CBG)
