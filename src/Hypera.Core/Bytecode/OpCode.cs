    Halt = 0x0001,

    // Constant & Register Moves
    LoadIntImm = 0x0010,
    LoadIntConst = 0x0011,
    LoadStrConst = 0x0012,
    MoveInt = 0x0013,
    MoveStr = 0x0014,

    // 64-bit Integer Arithmetic, Bitwise & Comparisons
    AddInt = 0x0020,
    SubInt = 0x0021,
    MulInt = 0x0022,
    DivInt = 0x0023,
    ModInt = 0x0024,
    NegInt = 0x0025,
    PowerInt = 0x0026,
    TimesFloat = 0x0027,
    BitAnd = 0x0028,
    BitOr = 0x0029,
    BitXor = 0x002A,
    BitNot = 0x002B,
    ShiftLeft = 0x002C,
    ShiftRight = 0x002D,
    UnsignedShiftRight = 0x002E,
    LogicalAnd = 0x0030,
    LogicalOr = 0x0031,
    LogicalNot = 0x0032,
    CmpEqInt = 0x0033,
    CmpNeInt = 0x0034,
    CmpLtInt = 0x0035,
    CmpLeInt = 0x0036,
    CmpGtInt = 0x0037,
    CmpGeInt = 0x0038,
    SelectInt = 0x0039,

    // String & StrForm Building
    ConcatStr = 0x0040,
    CmpEqStr = 0x0041,
    CmpNeStr = 0x0042,
    CmpLtStr = 0x0043,
    CmpLeStr = 0x0044,
    CmpGtStr = 0x0045,
    CmpGeStr = 0x0046,
    SelectStr = 0x0047,
    ToStr = 0x0048,
    ToInt = 0x0049,
    StrFormBegin = 0x004A,
    StrFormAppendLiteral = 0x004B,
    StrFormAppendInt = 0x004C,
    StrFormAppendStr = 0x004D,
    StrFormAppendFormatted = 0x004E,
    StrFormBuild = 0x004F,

    // Static, Character & Ref Variable Slot Load/Store
    LoadStaticInt = 0x0060,
    StoreStaticInt = 0x0061,
    LoadStaticStr = 0x0062,
    StoreStaticStr = 0x0063,
    LoadStaticInt1D = 0x0064,
    StoreStaticInt1D = 0x0065,
    LoadStaticInt2D = 0x0066,
    StoreStaticInt2D = 0x0067,
    LoadStaticInt3D = 0x0068,
    StoreStaticInt3D = 0x0069,
    LoadStaticStr1D = 0x006A,
    StoreStaticStr1D = 0x006B,
    LoadStaticStr2D = 0x006C,
    StoreStaticStr2D = 0x006D,
    LoadStaticStr3D = 0x006E,
    StoreStaticStr3D = 0x006F,
    LoadCharaInt1D = 0x0070,
    StoreCharaInt1D = 0x0071,
    LoadCharaInt2D = 0x0072,
    StoreCharaInt2D = 0x0073,
    LoadCharaStr1D = 0x0074,
    StoreCharaStr1D = 0x0075,
    BindRefSlot = 0x0076,
    LoadRefInt = 0x0077,
    StoreRefInt = 0x0078,
    LoadRefStr = 0x0079,
    StoreRefStr = 0x007A,

    // Register Loop Superinstructions
    ForInit = 0x0080,
    ForStep = 0x0081,
    RepeatInit = 0x0082,
    RepeatStep = 0x0083,

    // Control Flow, Calls & Event Dispatch
    Jump = 0x0090,
    JumpIfTrue = 0x0091,
    JumpIfFalse = 0x0092,
    JumpTable = 0x0093,
    Call = 0x0094,
    CallDynamic = 0x0095,
    TryCall = 0x0096,
    CallEventGroup = 0x0097,
