    CbgClear = 0x00EC,

    // Extended Subsystems & Built-in Dispatch
    DataTableOp = 0x0100,
    XmlOp = 0x0101,
    MapOp = 0x0102,
    AudioOp = 0x0103,
    BuiltinCallInt = 0x0104,
    BuiltinCallStr = 0x0105,
    BuiltinInstruction = 0x0106,

    // Dynamic Runtime Evaluation Fallbacks (PRINTFORMS, STRFORM, RETURNFORM, GETVAR, SETVAR)
    DynamicEvalExprInt = 0x0120,
    DynamicEvalExprStr = 0x0121,
    DynamicEvalStrForm = 0x0122,
    DynamicGetVarInt = 0x0123,
    DynamicGetVarStr = 0x0124,
    DynamicSetVarInt = 0x0125,
    DynamicSetVarStr = 0x0126,
    DynamicExistVar = 0x0127,
    BeginDebugGuard = 0x0128,
}
